# Parse command line arguments
parse_args() {
    local tests_to_run=()
    
    while [[ $# -gt 0 ]]; do
        case $1 in
            -h)
                usage
                exit 0
                ;;
            -v)
                VERBOSE=true
                shift
                ;;
            -k)
                KEEP_OUTPUT_FILES=true
                shift
                ;;
        # We only support bigset right now, so no need to allow user to select tests.
        #  Expected to add these tests back in later.
            standard|bigset|sparse|remove)
                tests_to_run+=("$1")
                shift
                ;;
            -*)
                echo "Unknown option: $1"
                usage
                exit 1
                ;;
            *)
                echo "Unknown test: $1"
                echo "Valid tests: standard, bigset, sparse, remove"
                usage
                exit 1
                ;;
        esac
    done
    
    # If no tests specified, run all tests
    if [ ${#tests_to_run[@]} -eq 0 ]; then
        tests_to_run=("standard" "bigset" "sparse" "remove")
    fi
    
    # Export the tests array so other functions can use it
    selected_tests=("${tests_to_run[@]}")
} # parse_args()

# Main function to run the crash recovery test
main() {
    # Parse command line arguments first
    parse_args "$@"
    vprintf "========================================================================\n"
    vprintf "Running crash recovery test loop on tests: ${selected_tests[*]}\n"
    vprintf "========================================================================\n"
    echo "HDF5TestExpress = $HDF5TestExpress"

    for test_name in "${selected_tests[@]}"; do
        echo ""
        echo "########## Running test: $test_name ##########"

        configure_test_env "$test_name"
        # set up nested loop to handle all different configs that can be run in a test.
        local has_run=false # Needed to skip additional configs if ONLY_RUN_EACH_TEST_ONCE is true
        for generator_config in "${GENERATOR_CONFIGS[@]}"; do

            # Skip additional configs if ONLY_RUN_EACH_TEST_ONCE is true and this test has already run once.
            if $ONLY_RUN_EACH_TEST_ONCE && $has_run; then
                continue  # Skip THIS test's additional configs
            fi
    
            vprintf "\nTest Configuration:\n"
            vprintf "    Writer:           %s <delay> %s %s\n" "$CRASHER_TOOL" "$WRITER_TOOL" "$WRITER_OPTIONS"
            vprintf "    Validation:       %s && %s\n" "$H5LS $EXPECTED_H5_FILE" "$H5DUMP -pH $EXPECTED_H5_FILE"
            vprintf "    Expected files:   %s, %s.*\n" "$EXPECTED_H5_FILE" "$EXPECTED_UD_FILE"
            vprintf "    Recovery:         %s\n" "$RECOVERY_TOOL"
            vprintf "    H5Clear:          %s -s\n" "$H5CLEAR"
            
            if $REQUIRES_GENERATOR && [ -n "$generator_config" ]; then
                vprintf "    Generator:        %s %s\n" "$VFD_GENERATOR" "$generator_config"
            else
                vprintf "    Generator:        None\n"
            fi
            vprintf "\n"

            run_crash_recovery_loop

            has_run=true # Used to skip subsequent configurations for the same test
        done
    done    
    
    echo "Crash recovery test finished."
    echo "Total Critical Errors: $nerrors" # should only ever be 0 or 1
} # main()

main "$@" # Run the script
